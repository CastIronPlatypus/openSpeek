import { ENGINE_NEEDS_SERVER, type EngineId, type ServerStatus } from '../types';

export interface EngineInfo {
  name: string;
  where: string;
  blurb: string;
}

export const ENGINE_INFO: Record<EngineId, EngineInfo> = {
  phonon: {
    name: 'Phonon',
    where: 'on this device',
    blurb: 'Private and works offline. One-time ~65 MB download.',
  },
  'phonon-server': {
    name: 'Phonon',
    where: 'on server',
    blurb: 'Same voices, generated by the openSpeek server. Best for slower phones.',
  },
  edge: {
    name: 'Edge',
    where: 'online voices',
    blurb: 'Microsoft neural voices in many languages, exact word highlighting. Text is sent to Microsoft.',
  },
};

export function engineLabel(id: EngineId): string {
  return `${ENGINE_INFO[id].name} · ${ENGINE_INFO[id].where}`;
}

/** `null` status means "not known yet": server engines are then treated as unavailable. */
export function isEngineAvailable(id: EngineId, status: ServerStatus | null): boolean {
  if (!ENGINE_NEEDS_SERVER[id]) return true;
  if (!status?.reachable) return false;
  return id === 'edge' ? status.engines.edge : status.engines.phonon;
}

export function unavailableReason(id: EngineId, status: ServerStatus | null): string | null {
  if (isEngineAvailable(id, status)) return null;
  if (!status) return 'Checking the openSpeek server…';
  if (!status.reachable) return 'Needs the openSpeek server — see Settings';
  return 'The openSpeek server does not offer this engine';
}

/** URL import proxy prefix for the server's page fetcher; `''` serverUrl means same origin. */
export function serverFetchPrefix(serverUrl: string): string {
  return `${serverUrl.trim().replace(/\/+$/, '')}/api/fetch?url=`;
}
